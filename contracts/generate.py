"""Run from any directory; --check checks committed generated contracts for drift."""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from backend.app.domain.contracts import ContractBundle, ExtractionOutput


def ts_type(s):
    if "$ref" in s:
        return s["$ref"].rsplit("/", 1)[-1]
    if "const" in s:
        return json.dumps(s["const"], ensure_ascii=False)
    if "enum" in s:
        return " | ".join(json.dumps(x) for x in s["enum"])
    for key in ("anyOf", "oneOf"):
        if key in s:
            return " | ".join(ts_type(x) for x in s[key])
    kind = s.get("type")
    if kind == "object":
        if "properties" not in s:
            additional = s.get("additionalProperties", True)
            return "Record<string, " + (ts_type(additional) if isinstance(additional, dict) else "unknown") + ">"
        required = set(s.get("required", []))
        return "{ " + " ".join(json.dumps(k) + ("" if k in required else "?") + ": " + ts_type(v) + ";"
                                 for k, v in s["properties"].items()) + " }"
    if kind == "array":
        if "prefixItems" in s:
            return "[" + ", ".join(ts_type(x) for x in s["prefixItems"]) + "]"
        return "Array<" + ts_type(s.get("items", {})) + ">"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}.get(kind, "unknown")


def build():
    bundle = ContractBundle.model_json_schema()
    definitions = bundle["$defs"]
    extraction = ExtractionOutput.model_json_schema()
    extraction["$schema"] = "https://json-schema.org/draft/2020-12/schema"
    bundle["$schema"] = extraction["$schema"]
    components = json.loads(json.dumps(definitions).replace("#/$defs/", "#/components/schemas/"))
    ref = lambda name: {"$ref": "#/components/schemas/" + name}
    content = lambda name: {"application/json": {"schema": ref(name)}}
    paths = {}
    def operation(path, method, request, response, status="200", headers=(), implemented=False):
        params = [{"name": "X-Request-ID", "in": "header", "required": False, "schema": {"type":"string"}}]
        if "{id}" in path:
            params.append({"name":"id","in":"path","required":True,"schema":{"type":"string","format":"uuid"}})
        params.extend({"name":h,"in":"header","required":True,"schema":{"type":"string","minLength":1}} for h in headers)
        response_headers = {"X-Request-ID":{"description":"请求追踪ID", "schema":{"type":"string"}}}
        responses = {status: {"description":"成功" if implemented else "成功；计划接口，尚未实现", "content":content(response), "headers":response_headers}}
        for code in ("400", "403", "404", "405", "409", "422", "413", "500"):
            responses[code] = {"description":"统一错误结构", "content":content("ErrorResponse"), "headers":response_headers}
        op = {"operationId":method + "_" + path.strip("/").replace("/", "_").replace("{id}", "by_id"),
              "parameters":params,"responses":responses,"x-implemented":implemented}
        if request:
            op["requestBody"] = {"required":True,"content":content(request)}
        paths.setdefault(path, {})[method] = op
    operation("/candidates/{id}", "get", None, "Candidate")
    operation("/candidates/{id}", "patch", "PatchRequest", "Candidate")
    operation("/candidates/{id}/review", "post", "ReviewRequest", "Candidate")
    operation("/change-plans/{id}", "get", None, "ChangePlan")
    operation("/change-plans/{id}/apply", "post", "ApplyRequest", "ApplyResponse", headers=("Idempotency-Key",))
    # Export jobs are asynchronous; a job identity is sufficient at T02.
    operation("/exports", "post", "ExportRequest", "ExportAccepted", status="202", headers=("Idempotency-Key",))
    operation("/health", "get", None, "HealthResponse", implemented=True)
    operation("/bootstrap", "get", None, "BootstrapResponse", implemented=True)
    operation("/session/verify", "post", None, "SessionResponse", headers=("Origin","X-CSRF-Token"), implemented=True)
    paths["/session/verify"]["post"]["security"] = [{"LocalSessionCookie":[]}]
    api = {"openapi":"3.1.0","info":{"title":"青岛海运报价 V1 数据合同", "version":"1.0.0",
            "description":"T02业务合同及T04系统接口。x-implemented区分运行接口与计划接口，运行端OpenAPI仅列出已实现路由。"},
           "servers":[{"url":"/api/v1"}],"paths":paths,"components":{"schemas":components,
           "securitySchemes":{"LocalSessionCookie":{"type":"apiKey","in":"cookie","name":"asw_local_session",
               "description":"本机HttpOnly会话cookie；写请求另需受信Origin和对应X-CSRF-Token，不是局域网身份认证。"}}}}
    enums = {k: v["enum"] for k,v in definitions.items() if "enum" in v}
    types = "// Generated by contracts/generate.py; do not edit. Runtime validation remains server-owned.\n"
    types += "\n".join(f"export type {k} = {ts_type(v)};" for k,v in definitions.items()) + "\n"
    types += "\n".join(f"export const {k}Values = {json.dumps(v, ensure_ascii=False)} as const;" for k,v in enums.items()) + "\n"
    return {"contracts/schemas/contracts.schema.json":bundle,
            "contracts/schemas/extraction.schema.json":extraction,
            "contracts/openapi.json":api,"contracts/generated/contracts.ts":types,
            "config/enums-v1.generated.json":enums}


def main():
    check = argparse.ArgumentParser()
    check.add_argument("--check", action="store_true")
    args = check.parse_args()
    stale = []
    for name, data in build().items():
        output = data if isinstance(data, str) else json.dumps(data, ensure_ascii=False, indent=2) + "\n"
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != output:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(output, encoding="utf-8", newline="\n")
    if stale:
        raise SystemExit("STALE CONTRACTS: " + ", ".join(stale))
    print("Contract generation " + ("check passed" if args.check else "completed"))


if __name__ == "__main__":
    main()
